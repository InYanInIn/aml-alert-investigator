CREATE SCHEMA sim;

CREATE TABLE sim.world (
    only_row           boolean PRIMARY KEY DEFAULT true CHECK (only_row),
    seed               bigint NOT NULL,
    generation         uuid NOT NULL UNIQUE,
    persona_counts     jsonb NOT NULL,
    thresholds_source  text NOT NULL,
    segment_thresholds jsonb NOT NULL,
    system             text NOT NULL DEFAULT 'azure_profile' CHECK (system IN ('b4', 'azure_profile')),
    created_at         timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE sim.period (
    period_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_day         date NOT NULL,
    last_day          date NOT NULL,
    target_day        date NOT NULL,
    system            text NOT NULL CHECK (system IN ('history', 'b4', 'azure_profile')),
    investigation_cap integer NOT NULL CHECK (investigation_cap >= 0),
    cost_usd          numeric NOT NULL DEFAULT 0 CHECK (cost_usd >= 0),
    investigations    integer NOT NULL DEFAULT 0 CHECK (investigations >= 0),
    status            text NOT NULL CHECK (status IN ('running', 'done', 'failed')),
    started_at        timestamptz NOT NULL DEFAULT now(),
    finished_at       timestamptz,
    tape_sha256       text NOT NULL,
    truncated         boolean NOT NULL DEFAULT false,
    error             text,
    CHECK (last_day BETWEEN first_day - 1 AND target_day)
);
CREATE UNIQUE INDEX sim_one_running_period ON sim.period (status) WHERE status = 'running';

CREATE TABLE sim.block (
    account_id text PRIMARY KEY REFERENCES core.accounts,
    decided_on date NOT NULL,
    period_id  bigint NOT NULL REFERENCES sim.period
);

CREATE TABLE sim.alert_period (
    alert_id  bigint PRIMARY KEY REFERENCES core.alerts,
    period_id bigint NOT NULL REFERENCES sim.period
);
CREATE INDEX sim_alert_period_period_id ON sim.alert_period (period_id);

CREATE TABLE sim.decision (
    alert_id       bigint PRIMARY KEY REFERENCES sim.alert_period,
    recommendation text CHECK (recommendation IN ('close', 'escalate')),
    skip_reason     text CHECK (skip_reason IN ('investigation_cap', 'prior_paid_attempt')),
    CHECK ((recommendation IS NULL) <> (skip_reason IS NULL))
);

CREATE TABLE sim.account_display (
    account_id    text PRIMARY KEY REFERENCES core.accounts,
    opening_eur   numeric,
    external_kind text,
    CHECK ((opening_eur IS NULL) <> (external_kind IS NULL))
);

CREATE TABLE sim.azure_spend (
    generation   uuid NOT NULL,
    account_id   text NOT NULL,
    alert_date   date NOT NULL,
    ordinal      integer NOT NULL CHECK (ordinal > 0),
    period_id    bigint NOT NULL,
    kind         text NOT NULL CHECK (kind IN ('chat', 'embedding')),
    reserved_usd numeric NOT NULL CHECK (reserved_usd > 0),
    settled_usd  numeric CHECK (settled_usd BETWEEN 0 AND reserved_usd),
    PRIMARY KEY (generation, account_id, alert_date, ordinal)
);
CREATE INDEX sim_azure_spend_period ON sim.azure_spend (generation, period_id);

GRANT USAGE ON SCHEMA sim TO aml_app, aml_evaluator;
GRANT SELECT (only_row, persona_counts, thresholds_source, system, created_at)
    ON sim.world TO aml_app, aml_evaluator;
GRANT SELECT ON sim.period, sim.block, sim.alert_period, sim.decision, sim.account_display TO aml_app, aml_evaluator;
