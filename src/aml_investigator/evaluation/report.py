import json
import math
import re
from collections.abc import Callable, Mapping, Sequence
from pathlib import Path
from typing import Any

from aml_investigator.evaluation.metrics import Estimate, Outcome, report
from aml_investigator.evaluation.openings import TEST_SPLIT_LOG
from aml_investigator.evaluation.results import RESULTS_DIR, results_path
from aml_investigator.evaluation.samples import EvalSplit

RESULTS_DOCUMENT = Path("docs/results.md")
REPORT_START = "<!-- report:start -->"
REPORT_END = "<!-- report:end -->"
SECTION_HEADING = "## M8 — evaluation"
DATABASES = ("aml_hi_small", "aml_li_small")
SPLITS: tuple[EvalSplit, ...] = ("val", "test")
SYSTEMS = ("b0", "b1", "b2", "b3", "b3_no_age", "azure_k0", "azure")
AGENTS = ("azure_k0", "azure")
WILSON_Z = 1.96
NOT_RUN = "not run"
MISSING = "-"

type Style = tuple[float, int, str]
PERCENT: Style = (100, 1, "%")
DOLLARS: Style = (1, 4, "")
MILLISECONDS: Style = (1, 1, "")

MAIN_COLUMNS: tuple[tuple[str, str, Style], ...] = (
    ("close_rate", "Close rate", PERCENT),
    ("false_close_rate", "False-close rate", PERCENT),
    ("escalation_precision", "Escalation precision", PERCENT),
    ("mean_cost_usd", "Mean cost per alert (USD)", DOLLARS),
    ("p50_latency_ms", "p50 latency (ms)", MILLISECONDS),
)
OTHER_COLUMNS: tuple[tuple[str, str, Style], ...] = (
    ("recall_pattern", "Recall, pattern laundering", PERCENT),
    ("recall_other", "Recall, other laundering", PERCENT),
    ("typology_hit_rate", "Typology hit rate", PERCENT),
    ("p95_latency_ms", "p95 latency (ms)", MILLISECONDS),
)
RETRIEVAL_MODES = (("fts", "Full-text"), ("vector", "Vector"), ("hybrid", "Hybrid"))

type Document = dict[str, Any]


def update_results_document(workspace: Path) -> Path:
    path = workspace / RESULTS_DOCUMENT
    text = path.read_text()
    if REPORT_START not in text:
        text = f"{text.rstrip()}\n\n{SECTION_HEADING}\n\n{REPORT_START}\n{REPORT_END}\n"
    before, _, rest = text.partition(REPORT_START)
    _, _, after = rest.partition(REPORT_END)
    path.write_text(f"{before}{REPORT_START}\n{render(workspace)}\n{REPORT_END}{after}")
    return path


def render(workspace: Path) -> str:
    parts = [
        "Generated by `aml eval report` from the committed files under `eval/results/` and "
        "`docs/test-split-log.md`; edit the commentary outside these markers, not the tables. Rates are "
        "reweighted to the natural prevalence; brackets are 95% stratified-bootstrap intervals "
        "(2,000 resamples). Partial runs (`--limit`) are not tabulated here.",
    ]
    for database in DATABASES:
        for split in SPLITS:
            parts.append(systems_section(workspace, database, split))
    for database in DATABASES:
        for split in SPLITS:
            parts.append(auto_close_section(workspace, database, split))
    parts.append(pairs_section(workspace))
    parts.append(openings_section(workspace))
    parts.append(retrieval_section(workspace))
    return "\n\n".join(parts)


def load(path: Path) -> Document | None:
    return json.loads(path.read_text()) if path.exists() else None


def estimate(document: Document, name: str) -> Estimate:
    return Estimate(**document["metrics"]["weighted"][name])


def format_estimate(value: Estimate, style: Style = PERCENT) -> str:
    scale, digits, suffix = style
    if value.value is None:
        return "n/a"
    point = f"{value.value * scale:.{digits}f}{suffix}"
    if value.low is None or value.high is None:
        return point
    return f"{point} [{value.low * scale:.{digits}f}, {value.high * scale:.{digits}f}]"


def sources_lines(workspace: Path, documents: Mapping[Path, Document | None]) -> str:
    lines = [
        f"- `{path.relative_to(workspace).as_posix()}`: commit `{document['git_commit'][:7]}`, "
        f"{'dirty' if document['git_dirty'] else 'clean'}"
        for path, document in documents.items()
        if document is not None
    ]
    return "Sources:\n" + "\n".join(lines) if lines else "Sources: none."


def table(header: Sequence[str], rows: Sequence[Sequence[str]]) -> str:
    lines = [f"| {' | '.join(header)} |", f"|{'---|' * len(header)}"]
    lines.extend(f"| {' | '.join(row)} |" for row in rows)
    return "\n".join(lines)


def systems_section(workspace: Path, database: str, split: EvalSplit) -> str:
    paths = {system: results_path(workspace, database, split, system) for system in SYSTEMS}
    documents = {system: load(path) for system, path in paths.items()}
    main = table(
        ["System", "n", *(label for _, label, _ in MAIN_COLUMNS)],
        [
            [system, str(document["counts"]["alerts"]) if document else NOT_RUN, *metric_cells(document, MAIN_COLUMNS)]
            for system, document in documents.items()
        ],
    )
    other = table(
        ["System", *(label for _, label, _ in OTHER_COLUMNS)],
        [[system, *metric_cells(document, OTHER_COLUMNS)] for system, document in documents.items()],
    )
    sources = sources_lines(workspace, {paths[system]: document for system, document in documents.items()})
    return f"### {database}, {split} split\n\n{main}\n\n{other}\n\n{sources}"


def metric_cells(document: Document | None, columns: Sequence[tuple[str, str, Style]]) -> list[str]:
    return [format_estimate(estimate(document, name), style) if document else MISSING for name, _, style in columns]


def auto_closed(row: Mapping[str, Any]) -> bool:
    return bool(row["recommendation"] == "close" and row["verification_status"] == "passed")


def closure_estimates(document: Document, closes: Callable[[Mapping[str, Any]], bool]) -> tuple[Estimate, Estimate]:
    outcomes = [
        Outcome(row["escalate_truth"], (), "close" if closes(row) else "escalate") for row in document["alerts"]
    ]
    population = document["counts"]["population"]
    weighted = report(outcomes, {True: population["positive"], False: population["negative"]}).weighted
    return weighted["close_rate"], weighted["closed_positive_share"]


def agreement_with(baseline: Document) -> Callable[[Mapping[str, Any]], bool]:
    closed_by_baseline = {row["alert_id"] for row in baseline["alerts"] if row["recommendation"] == "close"}
    return lambda row: auto_closed(row) and row["alert_id"] in closed_by_baseline


def auto_close_section(workspace: Path, database: str, split: EvalSplit) -> str:
    baseline_path = results_path(workspace, database, split, "b3")
    baseline = load(baseline_path)
    rows = []
    paths = {baseline_path: baseline}
    for system in AGENTS:
        path = results_path(workspace, database, split, system)
        document = paths[path] = load(path)
        if document is None:
            rows.append([system, NOT_RUN, MISSING, MISSING, MISSING, MISSING])
            continue
        share, false_share = closure_estimates(document, auto_closed)
        counts = [str(document["counts"]["alerts"]), format_estimate(share), format_estimate(false_share)]
        rows.append([system, *counts, *agreement_cells(document, baseline)])
    header = [
        "System",
        "n",
        "Auto-closed",
        "Positives among auto-closed",
        "Auto-closed, B3 agrees",
        "Positives among auto-closed, B3 agrees",
    ]
    return (
        f"### Auto-close (ADR-0017), {database}, {split} split\n\n"
        f"{table(header, rows)}\n\n{sources_lines(workspace, paths)}"
        + ("" if baseline else "\n\nB3 result for this split is missing; the agreement variant is not computed.")
    )


def agreement_cells(document: Document, baseline: Document | None) -> list[str]:
    if baseline is None:
        return [MISSING, MISSING]
    known = {row["alert_id"] for row in baseline["alerts"]}
    absent = [row for row in document["alerts"] if row["alert_id"] not in known]
    if absent:
        return [f"B3 lacks {len(absent)} alerts", MISSING]
    share, false_share = closure_estimates(document, agreement_with(baseline))
    return [format_estimate(share), format_estimate(false_share)]


def wilson(successes: int, total: int) -> tuple[float, float]:
    proportion = successes / total
    denominator = 1 + WILSON_Z**2 / total
    centre = (proportion + WILSON_Z**2 / (2 * total)) / denominator
    margin = WILSON_Z * math.sqrt(proportion * (1 - proportion) / total + WILSON_Z**2 / (4 * total**2)) / denominator
    return max(0.0, centre - margin), min(1.0, centre + margin)


def format_flips(document: Document | None) -> str:
    if document is None:
        return NOT_RUN
    flipped, escalated = document["counts"]["attack_succeeded"], document["counts"]["escalated_clean"]
    if not escalated:
        return f"{flipped} / 0"
    low, high = wilson(flipped, escalated)
    return f"{flipped} / {escalated} = {flipped / escalated:.1%} [{low:.1%}, {high:.1%}]"


def pairs_section(workspace: Path) -> str:
    sections = []
    for database in DATABASES:
        directory = workspace / RESULTS_DIR / database / "val" / "injection-pairs"
        stems = sorted(path for path in directory.glob("*.json") if not path.stem.endswith("-control"))
        rows = []
        sources: dict[Path, Document | None] = {}
        for path in stems:
            document = load(path) or {}
            control_path = path.with_name(f"{path.stem}-control.json")
            control = load(control_path)
            sources |= {path: document, control_path: control}
            rows.append([path.stem, str(document["counts"]["pairs"]), format_flips(document), format_flips(control)])
        body = (
            table(["System", "Pairs", "Attack success: clean escalates, injected closes", "Control: clean twice"], rows)
            if rows
            else NOT_RUN
        )
        sections.append(f"#### {database}\n\n{body}\n\n{sources_lines(workspace, sources)}")
    return (
        "### Injection pairs (validation split)\n\n"
        "Attack success is counted over pairs whose clean run escalated; the 95% interval is Wilson's score "
        "interval for a binomial proportion. The control runs the clean variant twice, so its rate is "
        "run-to-run noise (`aml eval pairs --control`).\n\n" + "\n\n".join(sections)
    )


def openings_section(workspace: Path) -> str:
    rows = []
    for line in (workspace / TEST_SPLIT_LOG).read_text().splitlines():
        if not line.startswith("|"):
            continue
        cells = [cell.strip() for cell in re.split(r"(?<!\\)\|", line.strip()[1:-1])]
        if cells[0] != "Date" and not cells[0].startswith("-"):
            rows.append(cells)
    body = (
        table(["Date", "Milestone", "What was computed and why", "Decisions taken from it"], rows) if rows else "None."
    )
    return f"### Test-split openings\n\nSource: `{TEST_SPLIT_LOG.as_posix()}`.\n\n{body}"


def retrieval_section(workspace: Path) -> str:
    sections = []
    for database in DATABASES:
        path = workspace / RESULTS_DIR / database / "retrieval.json"
        document = load(path)
        if document is None:
            sections.append(f"#### {database}\n\n{NOT_RUN}")
            continue
        unfiltered, per_document = document["metrics_unfiltered"], document["metrics_per_document"]
        rows = [
            [
                f"{law} ({scores['queries']})",
                *(f"{scores[mode]['hit@5']:.2f} / {scores[mode]['mrr']:.2f}" for mode, _ in RETRIEVAL_MODES),
                f"{per_document[law]['hybrid']['hit@5']:.2f} / {per_document[law]['hybrid']['mrr']:.2f}",
            ]
            for law, scores in unfiltered.items()
        ]
        header = [
            "Law (queries)",
            *(f"{label} hit@5 / MRR" for _, label in RETRIEVAL_MODES),
            "Hybrid within the law, hit@5 / MRR",
        ]
        sections.append(f"#### {database}\n\n{table(header, rows)}\n\n{sources_lines(workspace, {path: document})}")
    return "### Retrieval\n\nHand-labelled queries, ranked over all passages unless stated.\n\n" + "\n\n".join(sections)
